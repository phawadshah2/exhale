import 'package:exhale/features/habit/domain/entities/habit.dart';

/// Stored by name, so values can be added but never renamed.
enum SmokeTrigger {
  coffee,
  stress,
  afterMeal,
  social,
  boredom,
  habit,
  commute,
  drinks,
  work,
  tired,
  morning,
  lateNight,
  bedtime,
  lonely,
  celebrating,
  studying,
  workout,
  watchingTv,
  notification,
  avoidingTasks,
}

extension HabitTriggers on HabitKind {
  /// The triggers offered for this habit, most common first.
  List<SmokeTrigger> get triggers => switch (this) {
    HabitKind.smoking => const [
      SmokeTrigger.coffee,
      SmokeTrigger.stress,
      SmokeTrigger.afterMeal,
      SmokeTrigger.social,
      SmokeTrigger.boredom,
      SmokeTrigger.habit,
      SmokeTrigger.commute,
      SmokeTrigger.drinks,
    ],
    HabitKind.vaping => const [
      SmokeTrigger.stress,
      SmokeTrigger.boredom,
      SmokeTrigger.social,
      SmokeTrigger.work,
      SmokeTrigger.afterMeal,
      SmokeTrigger.coffee,
      SmokeTrigger.commute,
      SmokeTrigger.habit,
    ],
    HabitKind.nicotinePouches => const [
      SmokeTrigger.work,
      SmokeTrigger.stress,
      SmokeTrigger.coffee,
      SmokeTrigger.afterMeal,
      SmokeTrigger.studying,
      SmokeTrigger.commute,
      SmokeTrigger.boredom,
      SmokeTrigger.habit,
    ],
    HabitKind.alcohol => const [
      SmokeTrigger.social,
      SmokeTrigger.stress,
      SmokeTrigger.afterMeal,
      SmokeTrigger.celebrating,
      SmokeTrigger.lonely,
      SmokeTrigger.tired,
      SmokeTrigger.boredom,
      SmokeTrigger.habit,
    ],
    HabitKind.caffeine => const [
      SmokeTrigger.morning,
      SmokeTrigger.tired,
      SmokeTrigger.work,
      SmokeTrigger.afterMeal,
      SmokeTrigger.studying,
      SmokeTrigger.stress,
      SmokeTrigger.social,
      SmokeTrigger.habit,
    ],
    HabitKind.energyDrinks => const [
      SmokeTrigger.tired,
      SmokeTrigger.work,
      SmokeTrigger.studying,
      SmokeTrigger.workout,
      SmokeTrigger.morning,
      SmokeTrigger.stress,
      SmokeTrigger.boredom,
      SmokeTrigger.habit,
    ],
    HabitKind.junkFood => const [
      SmokeTrigger.stress,
      SmokeTrigger.boredom,
      SmokeTrigger.watchingTv,
      SmokeTrigger.lateNight,
      SmokeTrigger.tired,
      SmokeTrigger.lonely,
      SmokeTrigger.social,
      SmokeTrigger.habit,
    ],
    HabitKind.socialMedia => const [
      SmokeTrigger.boredom,
      SmokeTrigger.bedtime,
      SmokeTrigger.morning,
      SmokeTrigger.avoidingTasks,
      SmokeTrigger.notification,
      SmokeTrigger.lonely,
      SmokeTrigger.stress,
      SmokeTrigger.habit,
    ],
    HabitKind.custom => const [
      SmokeTrigger.stress,
      SmokeTrigger.boredom,
      SmokeTrigger.social,
      SmokeTrigger.tired,
      SmokeTrigger.work,
      SmokeTrigger.lonely,
      SmokeTrigger.afterMeal,
      SmokeTrigger.habit,
    ],
  };
}
