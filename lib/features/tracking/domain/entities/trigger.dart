import 'package:exhale/features/habit/domain/entities/habit.dart';

/// Stored by name, so values can be added but never renamed.
enum Trigger {
  coffee,
  stress,
  afterMeal,
  social,
  boredom,
  habit,
  commute,
  drinks,
  work,
  tired,
  morning,
  lateNight,
  bedtime,
  lonely,
  celebrating,
  studying,
  workout,
  watchingTv,
  notification,
  avoidingTasks,
}

extension HabitTriggers on HabitKind {
  /// The triggers offered for this habit, most common first.
  List<Trigger> get triggers => switch (this) {
    HabitKind.smoking => const [
      Trigger.coffee,
      Trigger.stress,
      Trigger.afterMeal,
      Trigger.social,
      Trigger.boredom,
      Trigger.habit,
      Trigger.commute,
      Trigger.drinks,
    ],
    HabitKind.vaping => const [
      Trigger.stress,
      Trigger.boredom,
      Trigger.social,
      Trigger.work,
      Trigger.afterMeal,
      Trigger.coffee,
      Trigger.commute,
      Trigger.habit,
    ],
    HabitKind.nicotinePouches => const [
      Trigger.work,
      Trigger.stress,
      Trigger.coffee,
      Trigger.afterMeal,
      Trigger.studying,
      Trigger.commute,
      Trigger.boredom,
      Trigger.habit,
    ],
    HabitKind.alcohol => const [
      Trigger.social,
      Trigger.stress,
      Trigger.afterMeal,
      Trigger.celebrating,
      Trigger.lonely,
      Trigger.tired,
      Trigger.boredom,
      Trigger.habit,
    ],
    HabitKind.caffeine => const [
      Trigger.morning,
      Trigger.tired,
      Trigger.work,
      Trigger.afterMeal,
      Trigger.studying,
      Trigger.stress,
      Trigger.social,
      Trigger.habit,
    ],
    HabitKind.energyDrinks => const [
      Trigger.tired,
      Trigger.work,
      Trigger.studying,
      Trigger.workout,
      Trigger.morning,
      Trigger.stress,
      Trigger.boredom,
      Trigger.habit,
    ],
    HabitKind.junkFood => const [
      Trigger.stress,
      Trigger.boredom,
      Trigger.watchingTv,
      Trigger.lateNight,
      Trigger.tired,
      Trigger.lonely,
      Trigger.social,
      Trigger.habit,
    ],
    HabitKind.socialMedia => const [
      Trigger.boredom,
      Trigger.bedtime,
      Trigger.morning,
      Trigger.avoidingTasks,
      Trigger.notification,
      Trigger.lonely,
      Trigger.stress,
      Trigger.habit,
    ],
    HabitKind.custom => const [
      Trigger.stress,
      Trigger.boredom,
      Trigger.social,
      Trigger.tired,
      Trigger.work,
      Trigger.lonely,
      Trigger.afterMeal,
      Trigger.habit,
    ],
  };
}
